def estimativas_financeiras(data, metricas_anteriores=None):
    print("\n=== EXPANSAO 5: ESTIMATIVAS FINANCEIRAS ===")
    orders_full = data["orders_full"].copy()
    delivered = orders_full[orders_full["order_status"] == "delivered"].dropna(
        subset=["total_order_value"])

    total_receita = delivered["total_order_value"].sum()
    total_clientes = delivered["customer_unique_id"].nunique()
    ticket_medio = delivered["total_order_value"].mean()
    total_pedidos = delivered["order_id"].nunique()

    customer_orders = delivered.groupby("customer_unique_id")["order_id"].nunique()
    clientes_recompra = (customer_orders > 1).sum()
    taxa_recompra_atual = clientes_recompra / total_clientes * 100

    # Cenario 1: Dobrar taxa de recompra (3% -> 6%)
    novos_recompra = int(total_clientes * 0.03)  # 3% adicionais
    receita_incremental_recompra = novos_recompra * ticket_medio
    pct_aumento_recompra = receita_incremental_recompra / total_receita * 100

    # Cenario 2: Reduzir atrasos em 50%
    atrasados = delivered[delivered["is_late"] == True]
    score_medio_atrasado = atrasados["review_score"].mean() if len(atrasados) > 0 else 3
    pedidos_atrasados = len(atrasados)
    pedidos_salvos = int(pedidos_atrasados * 0.5)

    # Cenario 3: Aumentar ticket medio em 10% via cross-sell
    receita_incremental_crosssell = total_receita * 0.10
    pct_aumento_crosssell = 10.0

    # Cenario 4: Reduzir frete em categorias criticas
    main = data["main"].copy()
    main_del = main[main["order_status"] == "delivered"].copy()
    cat_freight = main_del.groupby("category").agg(
        preco_medio=("price", "mean"),
        frete_medio=("freight_value", "mean"),
        count=("order_id", "count"),
        receita=("price", "sum"),
    )
    cat_freight["frete_pct"] = cat_freight["frete_medio"] / cat_freight["preco_medio"] * 100
    cats_alto_frete = cat_freight[cat_freight["frete_pct"] > 30]
    receita_cats_alto_frete = cats_alto_frete["receita"].sum()
    # Estimativa: reduzir frete em 20% nessas categorias aumenta conversao em 5%
    receita_incremental_frete = receita_cats_alto_frete * 0.05

    # --- Grafico: Impacto financeiro estimado por iniciativa ---
    initiatives = {
        "Programa de\nRecompra\n(3% -> 6%)": receita_incremental_recompra,
        "Cross-Sell\nInteligente\n(+10% ticket)": receita_incremental_crosssell,
        "Otimizacao\nde Frete\n(cats criticas)": receita_incremental_frete,
    }

    fig, ax = plt.subplots(figsize=(12, 6))
    names = list(initiatives.keys())
    values = [v / 1_000_000 for v in initiatives.values()]
    colors_init = [PALETTE[2], PALETTE[0], PALETTE[1]]

    bars = ax.bar(names, values, color=colors_init, edgecolor="white", width=0.6)
    ax.set_ylabel("Receita Incremental Estimada (R$ milhoes)")
    ax.set_title("Impacto Financeiro Estimado por Iniciativa Estrategica", fontsize=14, fontweight="bold")
    for bar, val in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.02,
                f"R$ {val:.2f}M", ha="center", fontsize=12, fontweight="bold")
    ax.set_ylim(0, max(values) * 1.3)
    fig.tight_layout()
    save_fig(fig, "9_1_impacto_financeiro_iniciativas.png")

    # --- Grafico: Cenario de crescimento com iniciativas combinadas ---
    receita_total_incremental = sum(initiatives.values())
    receita_projetada_com_iniciativas = total_receita + receita_total_incremental

    fig, ax = plt.subplots(figsize=(10, 6))
    categories = ["Receita Atual\n(2016-2018)", "Com Recompra", "+ Cross-Sell", "+ Frete\n= PROJETADA"]
    cumulative = [
        total_receita,
        total_receita + receita_incremental_recompra,
        total_receita + receita_incremental_recompra + receita_incremental_crosssell,
        receita_projetada_com_iniciativas,
    ]
    cumulative_m = [v / 1_000_000 for v in cumulative]

    bars = ax.bar(categories, cumulative_m, color=[PALETTE[7], PALETTE[2], PALETTE[0], PALETTE[1]],
                  edgecolor="white", width=0.6)
    ax.set_ylabel("Receita (R$ milhoes)")
    ax.set_title("Receita Projetada com Iniciativas Estrategicas Combinadas",
                 fontsize=14, fontweight="bold")
    for bar, val in zip(bars, cumulative_m):
        ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height() + 0.1,
                f"R$ {val:.1f}M", ha="center", fontsize=11, fontweight="bold")

    # Mostrar incremento
    aumento_pct = (receita_projetada_com_iniciativas - total_receita) / total_receita * 100
    ax.annotate(f"+{aumento_pct:.1f}%", xy=(3, cumulative_m[3]),
                xytext=(3, cumulative_m[3] + 0.8),
                fontsize=14, fontweight="bold", color=PALETTE[2],
                ha="center", va="bottom",
                arrowprops=dict(arrowstyle="->", color=PALETTE[2]))

    fig.tight_layout()
    save_fig(fig, "9_2_receita_com_iniciativas.png")

    metricas = {
        "receita_incremental_recompra": receita_incremental_recompra,
        "receita_incremental_crosssell": receita_incremental_crosssell,
        "receita_incremental_frete": receita_incremental_frete,
        "receita_total_incremental": receita_total_incremental,
        "aumento_pct": aumento_pct,
        "pedidos_salvos_logistica": pedidos_salvos,
    }
    print(f"  Receita incremental total: R$ {receita_total_incremental:,.0f}")
    print(f"  Aumento projetado: +{aumento_pct:.1f}%")
    return metricas


