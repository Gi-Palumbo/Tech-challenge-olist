def previsao_robusta(data):
    print("\n=== EXPANSAO 3: PREVISAO ROBUSTA ===")
    orders_full = data["orders_full"].copy()
    delivered = orders_full[
        orders_full["order_status"].isin(["delivered", "shipped", "invoiced", "processing"])
    ].dropna(subset=["order_purchase_timestamp"]).copy()

    delivered["year_month"] = delivered["order_purchase_timestamp"].dt.to_period("M")
    monthly = delivered.groupby("year_month").agg(
        receita=("total_order_value", "sum"),
        pedidos=("order_id", "nunique"),
    ).reset_index()
    monthly["month_num"] = range(len(monthly))
    monthly["year_month_str"] = monthly["year_month"].astype(str)

    # Remover primeiro e ultimo mes (possivelmente incompletos)
    if len(monthly) > 4:
        monthly_clean = monthly.iloc[1:-1].copy()
    else:
        monthly_clean = monthly.copy()

    # Media movel de 3 meses
    monthly_clean["receita_mm3"] = monthly_clean["receita"].rolling(window=3, center=True).mean()

    # Tendencia linear
    x = monthly_clean["month_num"].values
    y = monthly_clean["receita"].values
    coeffs = np.polyfit(x, y, 1)
    trend = np.poly1d(coeffs)

    # Calcular sazonalidade (razao entre valor real e tendencia)
    monthly_clean["trend_value"] = trend(monthly_clean["month_num"])
    monthly_clean["seasonal_ratio"] = monthly_clean["receita"] / monthly_clean["trend_value"]
    monthly_clean["month_of_year"] = monthly_clean["year_month"].apply(lambda x: x.month)
    seasonal_factors = monthly_clean.groupby("month_of_year")["seasonal_ratio"].mean()

    # Projecao 6 meses com sazonalidade
    last_month_num = monthly.iloc[-1]["month_num"]
    last_period = monthly.iloc[-1]["year_month"]

    future_data = []
    for i in range(1, 7):
        month_num = last_month_num + i
        period = last_period + i
        month_of_year = period.month
        base_value = trend(month_num)
        seasonal_factor = seasonal_factors.get(month_of_year, 1.0)
        projected = base_value * seasonal_factor
        future_data.append({
            "year_month_str": str(period),
            "month_num": month_num,
            "receita_base": base_value,
            "receita_projetada": projected,
            "seasonal_factor": seasonal_factor,
        })

    future_df = pd.DataFrame(future_data)

    # Cenarios
    std_residual = (monthly_clean["receita"] - monthly_clean["trend_value"]).std()
    future_df["cenario_otimista"] = future_df["receita_projetada"] * 1.15
    future_df["cenario_pessimista"] = future_df["receita_projetada"] * 0.85

    # --- Grafico: Previsao com cenarios ---
    fig, ax = plt.subplots(figsize=(16, 7))

    # Realizado
    ax.bar(range(len(monthly)), monthly["receita"] / 1000, color=PALETTE[0], alpha=0.7, label="Realizado")

    # Media movel
    mm3_idx = monthly_clean.index.tolist()
    ax.plot([i + 1 for i in range(len(monthly_clean))],
            monthly_clean["receita_mm3"].values / 1000,
            color=PALETTE[4], linewidth=2.5, linestyle="-", label="Media Movel 3M", marker="")

    # Projecao
    future_x = [len(monthly) + i for i in range(len(future_df))]
    ax.bar(future_x, future_df["receita_projetada"] / 1000, color=PALETTE[1], alpha=0.6,
           label="Projecao (com sazonalidade)")

    # Cenarios
    ax.fill_between(future_x,
                    future_df["cenario_pessimista"] / 1000,
                    future_df["cenario_otimista"] / 1000,
                    alpha=0.2, color=PALETTE[1], label="Intervalo Otimista/Pessimista (+/-15%)")

    # Linha de tendencia
    all_x = list(range(len(monthly) + len(future_df)))
    ax.plot(all_x, trend(all_x) / 1000, color=PALETTE[3], linestyle="--", linewidth=1.5,
            label="Tendencia Linear")

    all_labels = list(monthly["year_month_str"]) + list(future_df["year_month_str"])
    ax.set_xticks(range(0, len(all_labels), 2))
    ax.set_xticklabels([all_labels[i] for i in range(0, len(all_labels), 2)], rotation=45, ha="right")
    ax.set_xlabel("Mes")
    ax.set_ylabel("Receita (R$ mil)")
    ax.set_title("Previsao de Receita com Sazonalidade e Cenarios", fontsize=15, fontweight="bold")
    ax.legend(loc="upper left", fontsize=9)

    # Anotacao na area de projecao
    ax.axvline(x=len(monthly) - 0.5, color="gray", linestyle=":", alpha=0.7)
    ax.text(len(monthly) + 1, ax.get_ylim()[1] * 0.95, "PROJECAO", fontsize=11,
            color="gray", fontweight="bold", ha="center")

    fig.tight_layout()
    save_fig(fig, "7_1_previsao_cenarios.png")

    # --- Grafico: Fatores de sazonalidade ---
    fig, ax = plt.subplots(figsize=(10, 5))
    month_names = ["Jan", "Fev", "Mar", "Abr", "Mai", "Jun",
                   "Jul", "Ago", "Set", "Out", "Nov", "Dez"]
    available_months = sorted(seasonal_factors.index)
    labels = [month_names[m - 1] for m in available_months]
    values = [seasonal_factors[m] for m in available_months]
    colors_season = [PALETTE[2] if v >= 1 else PALETTE[3] for v in values]

    ax.bar(labels, values, color=colors_season, edgecolor="white")
    ax.axhline(y=1.0, color="gray", linestyle="--", alpha=0.7, label="Neutro (1.0)")
    ax.set_xlabel("Mes")
    ax.set_ylabel("Fator de Sazonalidade")
    ax.set_title("Fatores de Sazonalidade Mensal", fontsize=14, fontweight="bold")
    ax.legend()
    for i, v in enumerate(values):
        ax.text(i, v + 0.02, f"{v:.2f}", ha="center", fontsize=9)
    fig.tight_layout()
    save_fig(fig, "7_2_sazonalidade.png")

    receita_projetada_6m = future_df["receita_projetada"].sum()
    metricas = {
        "receita_projetada_6m": receita_projetada_6m,
        "crescimento_mensal_tendencia": coeffs[0],
        "cenario_otimista_6m": future_df["cenario_otimista"].sum(),
        "cenario_pessimista_6m": future_df["cenario_pessimista"].sum(),
    }
    print(f"  Receita projetada (6 meses): R$ {receita_projetada_6m:,.0f}")
    print(f"  Cenario otimista: R$ {metricas['cenario_otimista_6m']:,.0f}")
    print(f"  Cenario pessimista: R$ {metricas['cenario_pessimista_6m']:,.0f}")
    return metricas


